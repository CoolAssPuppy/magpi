#!/usr/bin/env node
/**
 * Writes api/supabase/functions/.env from Doppler.
 *
 * Local edge functions do not read Doppler and do not inherit the shell that
 * started the stack. They read this file, so without it every OAuth connect
 * answers 503 provider_unconfigured while the credentials sit in Doppler
 * looking correct.
 *
 * SUPABASE_URL and the keys are injected by the runtime, so they are not
 * written here.
 *
 *   pnpm secrets:local
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const TARGET = join(root, "api", "supabase", "functions", ".env");

/** Every name a function reads that the runtime does not provide. */
const NAMES = [
  "TOKEN_ENCRYPTION_KEY",
  "TOKEN_ENCRYPTION_KEY_ID",
  "TOKEN_ENCRYPTION_KEYS_PREVIOUS",
  "WEB_BASE_URL",
  "WEB_ORIGINS",
  "PAIRING_URL",
];

/** providerCredentials() builds these from the slug, so they are listed here. */
const PROVIDERS = ["google", "github", "linear", "slack", "notion"];
for (const slug of PROVIDERS) {
  NAMES.push(`OAUTH_${slug.toUpperCase()}_CLIENT_ID`);
  NAMES.push(`OAUTH_${slug.toUpperCase()}_CLIENT_SECRET`);
}

function read(name) {
  try {
    return execFileSync(
      "doppler",
      ["secrets", "get", name, "--plain", "--project", "magpi", "--config", "dev"],
      { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] },
    ).replace(/\n$/, "");
  } catch {
    return "";
  }
}

const lines = [
  "# Generated by pnpm secrets:local. Not committed: this file holds secrets.",
  "# Regenerate after changing anything in Doppler, then restart the stack so",
  "# the edge runtime picks it up.",
];
let missing = 0;
for (const name of NAMES) {
  const value = read(name);
  if (!value) missing += 1;
  lines.push(`${name}=${value}`);
}

writeFileSync(TARGET, lines.join("\n") + "\n", { mode: 0o600 });
process.stdout.write(
  `wrote ${NAMES.length} names to api/supabase/functions/.env` +
    (missing > 0 ? `, ${missing} of them empty\n` : "\n"),
);
