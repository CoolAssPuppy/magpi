#!/usr/bin/env node
/** Regenerates web/components/brand/source-icons.tsx from simple-icons. */

import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(ROOT, 'web/components/brand/source-icons.tsx');

const icons = require('simple-icons');

/** Provider slug to the simple-icons export that carries its official mark. */
const FROM_SIMPLE_ICONS = {
  notion: 'siNotion',
  linear: 'siLinear',
  google_drive: 'siGoogledrive',
};

/** Ours, for a document somebody dragged in rather than one a tool sent. */
const HAND_DRAWN = {
  upload:
    'M12 2.6 5.6 9h4v6.8h4.8V9h4zM3.6 17.4v2.6c0 .8.6 1.4 1.4 1.4h14c.8 0 1.4-.6 1.4-1.4v-2.6h-2.4v1.6H6v-1.6z',
};

/**
 * Slack is four colours, so it cannot be a single path tinted by a token like the others. It is
 * vendored whole at web/public/brand/slack.svg and served from this origin, which the content
 * security policy allows.
 */
const VENDORED = { slack: '/brand/slack.svg' };

const ORDER = ['notion', 'linear', 'slack', 'google_drive', 'upload'];

function pathFor(slug) {
  const key = FROM_SIMPLE_ICONS[slug];
  if (!key) return HAND_DRAWN[slug];

  const icon = icons[key];
  if (!icon) throw new Error(`simple-icons has no ${key}, so ${slug} cannot be generated`);
  return icon.path;
}

const entries = ORDER.filter((slug) => !VENDORED[slug])
  .map((slug) => `  ${slug}: '${pathFor(slug)}',`)
  .join('\n');

const files = Object.entries(VENDORED)
  .map(([slug, href]) => `  ${slug}: '${href}',`)
  .join('\n');

const file = `// Generated by scripts/sync-source-icons.mjs. Do not edit by hand.
//
// The single path marks come from simple-icons, which is CC0. Slack is four colours and is
// vendored whole at web/public/brand/slack.svg.

export type SourceSlug = ${ORDER.map((s) => `'${s}'`).join(' | ')};

/** Marks drawn as one path, tinted with the identity colour in tokens.css. */
export const SOURCE_PATHS: Partial<Record<SourceSlug, string>> = {
${entries}
};

/** Marks that carry their own colours, served from this origin. */
export const SOURCE_FILES: Partial<Record<SourceSlug, string>> = {
${files}
};

export const SOURCE_SLUGS: readonly SourceSlug[] = [
${ORDER.map((s) => `  '${s}',`).join('\n')}
];
`;

writeFileSync(OUT, file);
console.log(`wrote ${OUT} with ${ORDER.length} marks`);
