#!/usr/bin/env node
/** Regenerates web/components/brand/source-icons.tsx from simple-icons. */

import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(ROOT, 'web/components/brand/source-icons.tsx');

const icons = require('simple-icons');

/** Provider slug to the simple-icons export that carries its official mark. */
const FROM_SIMPLE_ICONS = {
  notion: 'siNotion',
  linear: 'siLinear',
  google_drive: 'siGoogledrive',
};

/**
 * Slack asked simple-icons to remove their mark, so there is no freely licensed copy to vendor.
 * A hash stands in, because a Slack source is a channel and a channel is written #name. Drop the
 * official asset in here if the brand portal's terms are met.
 */
const HAND_DRAWN = {
  slack:
    'M9.4 2.6 8.1 8.1H3.3v2.4h4.2l-1 4.4H2.2v2.4h3.7l-1.3 5.5 2.3.6 1.4-6.1h4.3l-1.3 5.5 2.3.6 1.4-6.1h4.8v-2.4h-4.2l1-4.4h4.3V8.1h-3.7l1.3-5.5-2.3-.6-1.4 6.1h-4.3l1.3-5.5-2.3-.6zM9.9 10.5h4.3l-1 4.4H8.9z',
  upload:
    'M12 2.6 5.6 9h4v6.8h4.8V9h4zM3.6 17.4v2.6c0 .8.6 1.4 1.4 1.4h14c.8 0 1.4-.6 1.4-1.4v-2.6h-2.4v1.6H6v-1.6z',
};

const ORDER = ['notion', 'linear', 'slack', 'google_drive', 'upload'];

function pathFor(slug) {
  const key = FROM_SIMPLE_ICONS[slug];
  if (!key) return HAND_DRAWN[slug];

  const icon = icons[key];
  if (!icon) throw new Error(`simple-icons has no ${key}, so ${slug} cannot be generated`);
  return icon.path;
}

const entries = ORDER.map((slug) => `  ${slug}: '${pathFor(slug)}',`).join('\n');

const file = `// Generated by scripts/sync-source-icons.mjs. Do not edit by hand.
//
// The marks come from simple-icons, which is CC0, except Slack. Slack asked to be removed from
// that set, so the hash below stands in for it and is ours.

export type SourceSlug = ${ORDER.map((s) => `'${s}'`).join(' | ')};

export const SOURCE_PATHS: Record<SourceSlug, string> = {
${entries}
};

export const SOURCE_SLUGS: readonly SourceSlug[] = [
${ORDER.map((s) => `  '${s}',`).join('\n')}
];
`;

writeFileSync(OUT, file);
console.log(`wrote ${OUT} with ${ORDER.length} marks`);
